export function getPieceCells(piece: Piece): Point[] {
  return SHAPES[piece.kind][piece.rotation].map((cell) => ({
    x: piece.x + cell.x,
    y: piece.y + cell.y
  }));
}

export function rotateClockwise(rotation: Rotation): Rotation {
  return (((rotation + 1) % 4) as Rotation);
}

export function rotateCounterClockwise(rotation: Rotation): Rotation {
  return (((rotation + 3) % 4) as Rotation);
}

export function getKickTests(kind: TetrominoKind, from: Rotation, to: Rotation): Point[] {
  if (kind === 'O') {
    return [{ x: 0, y: 0 }];
  }

  const key = `${from}>${to}` as KickKey;
  return kind === 'I' ? I_KICKS[key] : JLSTZ_KICKS[key];
}
